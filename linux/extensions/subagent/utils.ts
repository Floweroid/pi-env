/**
 * 将 SubagentProcessResult（来自 spawn.ts）转换为 SingleResult。
 * overrides 提供 spawn 结果中不包含的字段。
 */
export function toSingleResult(
	result: {
		exitCode: number;
		output: string;
		stderr: string;
		usage: UsageStats;
		model?: string;
		stopReason?: string;
		errorMessage?: string;
	},
	overrides: {
		agent: string;
		agentSource: "user" | "project" | "unknown";
		task: string;
		step?: number;
	},
): SingleResult {
	return {
		agent: overrides.agent,
		agentSource: overrides.agentSource,
		task: overrides.task,
		exitCode: result.exitCode,
		messages: [],
		stderr: result.stderr,
		usage: result.usage,
		model: result.model,
		stopReason: result.stopReason,
		errorMessage: result.errorMessage,
		step: overrides.step,
	};
}

/** 发送包含子代理结果的 followUp 消息。 */
export function injectSubagentResult(
	pi: ExtensionAPI,
	agentName: string,
	result: { exitCode: number; output: string; id?: string },
): void {
	const status = result.exitCode === 0 ? "✅" : "❌";
	const idLine = result.id ? `[${result.id}] ` : "";
	pi.sendUserMessage(
		`${idLine}[subagent ${agentName}] ${status} 完成:\n\n${result.output}`,
		{ deliverAs: "followUp" },
	);
}

/** 格式化 agent 列表用于错误消息。 */
export function formatAgentList(agents: { name: string; source: string }[]): string {
	return agents.map((a) => `"${a.name}" (${a.source})`).join(", ") || "none";
}

/** 清除 TUI widget 及状态栏。 */
export function clearWidget(ui: ExtensionContext["ui"] | null, widgetId: string): void {
	ui?.setWidget(widgetId, undefined);
	ui?.setStatus(widgetId, undefined);
}

